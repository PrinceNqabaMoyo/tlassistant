def generate(archetype: Optional[str] = None, seed: Optional[int] = None, count: int = 1, **kwargs) -> List[Dict[str, Any]]:
    rng = random.Random(seed)
    results = []
    for idx in range(count):
        target = archetype or rng.choice(SUBSKILLS)
        if target == "photosynthesis_chemical_equation_and_inputs":
            item = _build_photosynthesis_equation(rng, seed, idx)
        elif target == "cellular_respiration_energy_release":
            item = _build_cellular_respiration(rng, seed, idx)
        elif target == "starch_test_investigation_method":
            item = _build_starch_test(rng, seed, idx)
        elif target == "carbon_dioxide_limewater_test":
            item = _build_limewater_test(rng, seed, idx)
        elif target == "chlorophyll_and_light_necessity_control":
            item = _build_chlorophyll_light_control(rng, seed, idx)
        else:
            item = _build_photosynthesis_equation(rng, seed, idx)
        results.append(item)
    return results


def get_archetypes() -> List[str]:
    return list(SUBSKILLS)
